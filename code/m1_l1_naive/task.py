"""Инцидент 1. Загрузчик, который "иногда теряет хвост".

Этот загрузчик написал ваш предшественник. Жалобы на него:
  - в некоторые дни в базе не хватает последних поездок, в другие дни все сходится;
  - однажды он крутился всю ночь и не остановился.

Почините fetch_all, не меняя ее параметры. После починки она должна:
  - запрашивать страницы с offset = 0, limit, 2*limit, ...;
  - останавливаться, когда пришла пустая страница, и возвращать все id в порядке получения;
  - если сделано max_pages запросов, а пустая страница так и не пришла,
    поднимать RuntimeError и больше запросов не делать.
Запрос, который вернул пустую страницу, тоже считается в max_pages.
Неполная страница - еще не конец: дождитесь пустой.

get_page(offset, limit) возвращает список id поездок (не больше limit штук),
за концом списка - пустой список. Объект API создавать не нужно: тесты сами передадут get_page.
"""


def fetch_all(get_page, limit, max_pages=1000):
    rows, offset = [], 0
    while True:
        page = get_page(offset, limit)
        if len(page) < limit:
            return rows
        rows += page
        offset += limit
