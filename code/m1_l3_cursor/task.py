"""Инцидент 3. Загрузчик, который закончил работу слишком рано.

API "ВелоКруга" перевели на закладки: get_page(before, limit) возвращает до limit id поездок,
которые меньше before, от больших к меньшим. before=None - с самого начала.
Если поездок больше нет - пустой список.

Коллега за пять минут переделал старый загрузчик под новый API. Ошибок нет,
но из шести поездок в базу попали три.

Почините fetch_all, не меняя ее параметры. После починки она должна:
  - первый запрос делать с before=None;
  - каждый следующий - с before, равным последнему id предыдущей страницы;
  - останавливаться на пустой странице и возвращать все id в порядке получения;
  - если сделано max_pages запросов, а пустая страница не пришла, поднимать RuntimeError.
Запрос, который вернул пустую страницу, тоже считается в max_pages.
Неполная страница - еще не конец: дождитесь пустой.
Объект API создавать не нужно: тесты сами передадут get_page.
"""


def fetch_all(get_page, limit, max_pages=1000):
    rows = []
    while True:
        page = get_page(len(rows) or None, limit)
        if not page:
            return rows
        rows += page
